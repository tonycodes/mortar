import { execFileSync } from "node:child_process";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";

export function unexpectedChanges(porcelain) {
  const allowed =
    /^(?:package\.json|package-lock\.json|catalog\.json|CHANGELOG\.md|manifests\/[^/]+\.json)$/;
  return porcelain
    .split(/\r?\n/)
    .filter(Boolean)
    .flatMap((line) => {
      const raw = line.slice(3);
      const paths = raw.split(" -> ").map((path) => {
        if (path.startsWith('"')) {
          try {
            return JSON.parse(path);
          } catch {
            return path;
          }
        }
        return path;
      });
      // Renames and copies are not generated by release preparation.
      return /[RC]/.test(line.slice(0, 2))
        ? paths
        : paths.filter((path) => !allowed.test(path));
    });
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  const unexpected = unexpectedChanges(
    execFileSync("git", ["status", "--porcelain", "--untracked-files=all"], {
      encoding: "utf8",
    }),
  );
  if (unexpected.length) {
    console.error(`Unexpected release changes:\n${unexpected.join("\n")}`);
    process.exitCode = 1;
  }
}
